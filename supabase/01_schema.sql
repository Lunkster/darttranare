-- 01: Schema dart – Darttränaren (2026-11-22)
--
-- Eget schema i Supabase-projektet tht (gratisplanen tillåter två aktiva projekt), som skytte.
-- Allt kräver inloggning med kontot som har rollen 'dart' i app_metadata. Ingen anonym läsning.
-- Spel får sitt id (uuid) i appen, så att de kan sparas offline och skickas upp senare.
-- Härledda värden (snitt, poäng, MPR) lagras aldrig – se 02_vyer.sql.

create schema if not exists dart;

create or replace function dart.ar_dart() returns boolean
  language sql stable set search_path = ''
  as $$ select coalesce(auth.jwt() -> 'app_metadata' ->> 'roll', '') = 'dart' $$;

create table dart.spelare (
  id       smallint generated by default as identity primary key,
  namn     text not null unique check (length(namn) between 1 and 40),
  aktiv    boolean not null default true,
  ordning  smallint not null default 0
);

-- Ett spel = en leg/omgång av en övning. Legs i samma match delar match_id.
create table dart.spel (
  id             uuid primary key,
  typ            text not null check (typ in ('x01', 'bobs27', 'dubbelrunda', 'jdc', 'scoring', 'cricket')),
  installningar  jsonb not null default '{}',     -- t.ex. {"start":501} eller {"mal":"20","pilar":100}
  start          timestamptz not null,
  slut           timestamptz,                      -- null = avbrutet/pågående
  match_id       uuid,
  kalla          text not null default 'app',      -- 'app' eller 'mdt' (import från My Dart Training)
  anteckning     text check (length(anteckning) <= 2000),
  andrad         timestamptz not null default now()
);
create index on dart.spel (start);

create table dart.spel_spelare (
  spel_id     uuid not null references dart.spel on delete cascade,
  spelare_id  smallint not null references dart.spelare,
  ordning     smallint not null,
  vinnare     boolean not null default false,
  resultat    jsonb,      -- bara för import utan pil-för-pil (t.ex. cricket: {"marks":24,"rundor":13}) eller motstånd {"mot":"CPU"}
  primary key (spel_id, spelare_id)
);

-- X01: en rad per besök (3 pilar). poang = 0 vid bust.
create table dart.runda (
  spel_id       uuid not null,
  spelare_id    smallint not null,
  nr            smallint not null check (nr between 1 and 200),
  poang         smallint not null check (poang between 0 and 180),
  pilar         smallint not null default 3 check (pilar between 1 and 3),
  pilar_dubbel  smallint not null default 0 check (pilar_dubbel between 0 and 3),
  checkout      boolean not null default false,
  primary key (spel_id, spelare_id, nr),
  foreign key (spel_id, spelare_id) references dart.spel_spelare on delete cascade
);

-- Övningar och cricket: en rad per pil. mal = det man siktade på ('20', 'D8', '25', 'D25'),
-- segment = där pilen hamnade ('S20', 'D20', 'T20', 'S25', 'D25', 'M' = miss).
create table dart.pil (
  spel_id     uuid not null,
  spelare_id  smallint not null,
  runda       smallint not null check (runda between 1 and 500),
  nr          smallint not null check (nr between 1 and 3),
  mal         text check (mal ~ '^[DT]?([1-9]|1[0-9]|20|25)$'),
  segment     text not null check (segment ~ '^(M|[SDT]([1-9]|1[0-9]|20)|[SD]25)$'),
  primary key (spel_id, spelare_id, runda, nr),
  foreign key (spel_id, spelare_id) references dart.spel_spelare on delete cascade
);

-- Rättigheter: bara inloggade med rollen dart
grant usage on schema dart to authenticated;
grant select, insert, update, delete on all tables in schema dart to authenticated;
revoke all on schema dart from anon;
alter table dart.spelare enable row level security;
alter table dart.spel enable row level security;
alter table dart.spel_spelare enable row level security;
alter table dart.runda enable row level security;
alter table dart.pil enable row level security;
create policy dart_alla on dart.spelare for all to authenticated using (dart.ar_dart()) with check (dart.ar_dart());
create policy dart_alla on dart.spel for all to authenticated using (dart.ar_dart()) with check (dart.ar_dart());
create policy dart_alla on dart.spel_spelare for all to authenticated using (dart.ar_dart()) with check (dart.ar_dart());
create policy dart_alla on dart.runda for all to authenticated using (dart.ar_dart()) with check (dart.ar_dart());
create policy dart_alla on dart.pil for all to authenticated using (dart.ar_dart()) with check (dart.ar_dart());

-- Spara ett helt spel i en transaktion (idempotent – samma spel kan skickas flera gånger från offline-kön).
-- p = {id, typ, installningar, start, slut, match_id, anteckning, spelare:[{spelare_id,ordning,vinnare,resultat}],
--      rundor:[{spelare_id,nr,poang,pilar,pilar_dubbel,checkout}], pilar:[{spelare_id,runda,nr,mal,segment}]}
create or replace function dart.spara_spel(p jsonb) returns uuid
  language plpgsql security invoker set search_path = ''
  as $$
declare sid uuid := (p ->> 'id')::uuid;
begin
  if not dart.ar_dart() then raise exception 'Ingen behörighet'; end if;
  insert into dart.spel (id, typ, installningar, start, slut, match_id, kalla, anteckning, andrad)
  values (sid, p ->> 'typ', coalesce(p -> 'installningar', '{}'), (p ->> 'start')::timestamptz, (p ->> 'slut')::timestamptz,
          (p ->> 'match_id')::uuid, coalesce(p ->> 'kalla', 'app'), p ->> 'anteckning', now())
  on conflict (id) do update set typ = excluded.typ, installningar = excluded.installningar, start = excluded.start,
    slut = excluded.slut, match_id = excluded.match_id, kalla = excluded.kalla, anteckning = excluded.anteckning, andrad = now();
  delete from dart.spel_spelare where spel_id = sid;   -- tar även rundor och pilar
  insert into dart.spel_spelare (spel_id, spelare_id, ordning, vinnare, resultat)
    select sid, x.spelare_id, x.ordning, coalesce(x.vinnare, false), x.resultat
    from jsonb_to_recordset(coalesce(p -> 'spelare', '[]')) as x(spelare_id smallint, ordning smallint, vinnare boolean, resultat jsonb);
  insert into dart.runda (spel_id, spelare_id, nr, poang, pilar, pilar_dubbel, checkout)
    select sid, x.spelare_id, x.nr, x.poang, coalesce(x.pilar, 3), coalesce(x.pilar_dubbel, 0), coalesce(x.checkout, false)
    from jsonb_to_recordset(coalesce(p -> 'rundor', '[]')) as x(spelare_id smallint, nr smallint, poang smallint, pilar smallint, pilar_dubbel smallint, checkout boolean);
  insert into dart.pil (spel_id, spelare_id, runda, nr, mal, segment)
    select sid, x.spelare_id, x.runda, x.nr, x.mal, x.segment
    from jsonb_to_recordset(coalesce(p -> 'pilar', '[]')) as x(spelare_id smallint, runda smallint, nr smallint, mal text, segment text);
  return sid;
end $$;

create or replace function dart.ta_bort_spel(sid uuid) returns void
  language plpgsql security invoker set search_path = ''
  as $$
begin
  if not dart.ar_dart() then raise exception 'Ingen behörighet'; end if;
  delete from dart.spel where id = sid;
end $$;

revoke execute on function dart.spara_spel(jsonb), dart.ta_bort_spel(uuid) from public, anon;
grant execute on function dart.spara_spel(jsonb), dart.ta_bort_spel(uuid), dart.ar_dart() to authenticated;
